const PRECOMPILED_GLOSSARY = SCIENCE_GLOSSARY.map((entry) => {
  const termLower = entry.term.toLowerCase();
  const escaped = termLower.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return {
    entry,
    termLower,
    regex: new RegExp(`\\b${escaped}s?\\b`, 'i'),
  };
});

/**
 * Finds up to `limit` helpful glossary terms that actually appear in a topic's
 * title, science explanation, or Qur'anic context so readers only see relevant words.
 */
export function extractKeyScienceWordsForTopic(
  combinedTopicText: string,
  explicitWords?: ScienceGlossaryWord[],
  limit = 4
): ScienceGlossaryWord[] {
  const results: ScienceGlossaryWord[] = [];
  const seen = new Set<string>();

  if (explicitWords && explicitWords.length > 0) {
    for (const item of explicitWords) {
      const k = item.term.toLowerCase();
      if (!seen.has(k)) {
        seen.add(k);
        results.push(item);
      }
      if (results.length >= limit) return results;
    }
  }

  const hay = combinedTopicText.toLowerCase();
  for (const { entry, termLower, regex } of PRECOMPILED_GLOSSARY) {
    if (seen.has(termLower)) continue;
    if (regex.test(hay)) {
      seen.add(termLower);
      results.push(entry);
      if (results.length >= limit) break;
    }
  }

  return results;
}
